function buildMenu(data) {
    const {
        userName,
        prefix,
        currentBotMode,
        systemStats,
        ping
    } = data;

    const botName = settings.botName || 'GAAJU-XMD';

    let version = String(settings.version || '3.0.5');

    if (!version.startsWith('v')) {
        version = `v${version}`;
    }

    const ownerName = settings.botOwner || 'Chris Gaaju';

    let menu = '';

    // UPDATED TOP INFORMATION SECTION
    menu += `╭━━〔 *${botName}* 〕\n`;
    menu += `┃ *User:* ${userName}\n`;
    menu += `┃ *Version:* ${version}\n`;
    menu += `┃ *Mode:* ${currentBotMode}\n`;
    menu += `┃ *Prefix:* ${prefix}\n`;
    menu += `┃ *Owner:* ${ownerName}\n`;
    menu += `┃ *Uptime:* ${systemStats.uptime}\n`;
    menu += `┃ *Speed:* ${ping}ms\n`;
    menu += `┃ *RAM:* ${systemStats.bar} ${systemStats.usagePercent}%\n`;
    menu += `╰━━━━━━━━━\n\n`;

    // READ MORE
    menu += READ_MORE;

    // SORT CATEGORIES ALPHABETICALLY
    const sortedCategoryNames = Object.keys(allCommandsRaw).sort(
        (a, b) => {
            const nameA = a.replace(/^[^\s]+\s/, '');
            const nameB = b.replace(/^[^\s]+\s/, '');

            return nameA.localeCompare(nameB);
        }
    );

    // READ MORE SEPARATORS
    const readMoreAfterCategories = new Set([2, 6, 10]);

    for (let i = 0; i < sortedCategoryNames.length; i++) {
        const title = sortedCategoryNames[i];
        const commands = allCommandsRaw[title];

        menu += `\n╭━━〔 *${title}* 〕\n`;

        if (
            commands.length > 0 &&
            typeof commands[0] === 'object' &&
            commands[0].sub
        ) {
            for (const sub of commands) {
                menu += `┃\n`;
                menu += `┃ ${sub.sub}\n`;

                for (const command of sortCommands(sub.cmds)) {
                    menu += `┃ ⤷ ${cleanCommand(command)}\n`;
                }
            }
        } else {
            for (const command of sortCommands(commands)) {
                menu += `┃ ⤷ ${cleanCommand(command)}\n`;
            }
        }

        menu += `╰━━━━━━━━━\n`;

        if (readMoreAfterCategories.has(i + 1)) {
            menu += `\n${READ_MORE}\n`;
        } else {
            menu += '\n';
        }
    }

    menu += '\n> Best WhatsApp Bot';

    return menu.trim();
}

