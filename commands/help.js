function getBotMode() {
    try {
        const filePath = path.join(__dirname, '../data/messageCount.json');

        if (fs.existsSync(filePath)) {
            const data = JSON.parse(
                fs.readFileSync(filePath, 'utf8')
            );

            if (typeof data.isPublic === 'boolean') {
                return data.isPublic ? 'Public' : 'Private';
            }
        }

        return 'Public';
    } catch (error) {
        return 'Public';
    }
}

