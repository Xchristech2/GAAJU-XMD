async function helpCommand(sock, chatId, message) {
    const senderId =
        message.key.participant ||
        message.key.remoteJid;

    let sendChatId = chatId;
    let realSenderJid = senderId;

    // SUPPORT FOR LID CHATS
    if (chatId.endsWith('@lid')) {
        const realJid = message.key.remoteJidAlt;

        if (realJid?.includes('@s.whatsapp.net')) {
            sendChatId = realJid;
            realSenderJid = realJid;
        }
    }

    const userName = await getUserName(
        sock,
        senderId,
        message
    );

    const prefix = getPrefix();
    const currentBotMode = getBotMode();
    const systemStats = getSystemStats();

    // MEASURE RESPONSE SPEED
    const start = Date.now();

    await sock.sendPresenceUpdate(
        'composing',
        chatId
    );

    const ping = Date.now() - start;

    // CHECK MENU MEDIA
    const imagePath = path.join(
        __dirname,
        '../assets/bot_image.jpg'
    );

    const gifPath = path.join(
        __dirname,
        '../assets/menu_video.mp4'
    );

    let menuType = 'Text';

    if (
        fs.existsSync(imagePath) &&
        fs.existsSync(gifPath)
    ) {
        menuType = Math.random() < 0.5
            ? 'Image'
            : 'GIF';
    } else if (fs.existsSync(imagePath)) {
        menuType = 'Image';
    } else if (fs.existsSync(gifPath)) {
        menuType = 'GIF';
    }

    // BUILD THE MENU
    const helpMessage = buildMenu({
        userName,
        prefix,
        currentBotMode,
        systemStats,
        ping
    });

    // PRESERVE FONT SUPPORT
    const fontId = getCurrentFont();

    const finalMessage = applyFont(
        helpMessage,
        fontId
    );

    // CHANNEL FORWARDING CONTEXT
    const channelCtx = {
        forwardingScore: 999,
        isForwarded: true,
        forwardedNewsletterMessageInfo: {
            newsletterJid: '120363406588763460@newsletter',
            newsletterName: '\u200E',
            serverMessageId: -1
        }
    };

    try {
        if (menuType === 'Image') {
            await sock.sendMessage(
                sendChatId,
                {
                    image: fs.readFileSync(imagePath),
                    caption: finalMessage,
                    mentions: [realSenderJid],
                    contextInfo: channelCtx
                },
                {
                    quoted: message
                }
            );
        } else if (menuType === 'GIF') {
            await sock.sendMessage(
                sendChatId,
                {
                    video: fs.readFileSync(gifPath),
                    mimetype: 'video/mp4',
                    gifPlayback: true,
                    caption: finalMessage,
                    mentions: [realSenderJid],
                    contextInfo: channelCtx
                },
                {
                    quoted: message
                }
            );
        } else {
            await sock.sendMessage(
                sendChatId,
                {
                    text: finalMessage,
                    mentions: [realSenderJid],
                    contextInfo: channelCtx
                },
                {
                    quoted: message
                }
            );
        }
    } catch (error) {
        console.error(
            'Error in help command:',
            error
        );

        await sock.sendMessage(
            sendChatId,
            {
                text: finalMessage,
                mentions: [realSenderJid]
            },
            {
                quoted: message
            }
        );
    }
}

