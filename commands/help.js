//                       USER NAME                          //
//══════════════════════════════════════════════════════════//

async function getUserName(sock, userId, message) {
    try {
        const pushName = message.pushName || message.key?.pushName;

        if (pushName) {
            return pushName;
        }

        const name = await sock.getName(userId);

        if (name && name !== userId) {
            return name;
        }

        return userId.split('@')[0] || 'User';
    } catch (error) {
        return userId.split('@')[0] || 'User';
    }
}

