function countTotalCommands() {
    let count = 0;

    for (const commands of Object.values(allCommandsRaw)) {
        if (
            commands.length > 0 &&
            typeof commands[0] === 'object' &&
            commands[0].sub
        ) {
            for (const sub of commands) {
                count += sub.cmds.length;
            }
        } else {
            count += commands.length;
        }
    }

    return count;
}

//══════════════════════════════════════════════════════════//
//                       COMMAND SORTING                    //
//══════════════════════════════════════════════════════════//

function sortCommands(commands) {
    return [...commands].sort((a, b) => {
        const nameA = a.replace(/^[ⓅⒻⒽⒹ]\s*/, '');
        const nameB = b.replace(/^[ⓅⒻⒽⒹ]\s*/, '');

        return nameA.localeCompare(nameB);
    });
}

function cleanCommand(command) {
    return command
        .replace(/^[ⓅⒻⒽⒹ]\s*/, '')
        .replace(/^[.!?/#-]+/, '');
}

